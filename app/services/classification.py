TOPIC_RULES: dict[str, tuple[str, ...]] = {
    topic: tuple(term for terms in subtopics.values() for term in terms)
    for topic, subtopics in TAXONOMY_RULES.items()
}
TOPIC_RULES["其他/综合"] = ()


@dataclass(frozen=True)
class RuleResult:
    topic: str
    subtopic: str
    keywords: str
    summary: str
    urgency: str
    confidence: float
    auxiliary_topics: tuple[str, ...] = ()


def classify_by_rule(title: str, content: str) -> RuleResult:
    text = f"{title}\n{content}"
    candidates: list[tuple[int, int, str, str, list[str]]] = []
    topic_hits: dict[str, set[str]] = {}
    for topic, subtopics in TAXONOMY_RULES.items():
        for subtopic, terms in subtopics.items():
            hits = [term for term in terms if term and term in text]
            if hits:
                topic_hits.setdefault(topic, set()).update(hits)
                candidates.append((len(hits), sum(len(term) for term in hits), topic, subtopic, hits))

    if not candidates:
        topic = "其他/综合"
        subtopic = ""
        hits: list[str] = []
        confidence = 0.2
        auxiliary: tuple[str, ...] = ()
    else:
        _, _, topic, subtopic, hits = max(candidates, key=lambda item: (item[0], item[1]))
        total_topic_hits = len(topic_hits[topic])
        hits = sorted(topic_hits[topic], key=lambda term: (-len(term), term))
        confidence = min(0.38 + 0.1 * total_topic_hits, 0.88)
        auxiliary = tuple(
            candidate_topic
            for candidate_topic, candidate_hits in sorted(
                topic_hits.items(), key=lambda item: len(item[1]), reverse=True
            )
            if candidate_topic != topic and candidate_hits
        )[:3]

    urgent_terms = ("紧急", "生命", "危险", "火灾", "漏电", "坍塌", "无法居住")
    urgency = "较急" if any(term in text for term in urgent_terms) else "一般"
    summary = title.strip()[:100] if title.strip() else content.strip()[:100]
    return RuleResult(
        topic=topic,
        subtopic=subtopic,
        keywords="、".join(hits[:8]),
        summary=summary,
        urgency=urgency,
        confidence=confidence,
        auxiliary_topics=auxiliary,
    )
